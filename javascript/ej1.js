//Realizamos una constante
const x = 10; //Una constante no podra cambiar su valor mas abajo en el código
let y = 10; //Let es una variable esta si es mutable entonces su valor podrá cambiar dentro del proceso del código
y  = 12; //El valor de la variable y ha cambiado de 10 a 12
var z = 5; //Var es una variable al igual let
z = 10; //Cambio su valor de 5 a 10

//A diferencia del let, var no hace caso al scope que mantienen las funciones, por ende este tiene un scope global
