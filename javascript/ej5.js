// JavaScript Objetos

//Creación de un objeto JavaScript
//Se pone entre llaves y los datos se guardan con clave: valor
const alumno = {
    nombre: "Nestor",
    apellidos: "Balderas Soto", 
    carrera: "Sistemas Computacionales"
}
//Imprimir todo el objeto
console.log(alumno);
//Imprimir datos especificos del objeto
console.log(alumno.nombre); //Accedemos unicamente al atributo nombre
console.log(alumno.apellidos); //Accedemos al atributo apellidos
console.log(alumno.carrera); //Accedemos al atributo carrera